/// Infer Go package name from existing .go sources (excluding *_test.go).
fn infer_go_package(wt: &Path) -> String {
    if let Ok(rd) = fs::read_dir(wt) {
        for ent in rd.flatten() {
            let p = ent.path();
            let name = p.file_name().and_then(|s| s.to_str()).unwrap_or("");
            if name.ends_with(".go") && !name.ends_with("_test.go") {
                if let Ok(content) = fs::read_to_string(&p) {
                    for line in content.lines() {
                        let line = line.trim();
                        if let Some(rest) = line.strip_prefix("package ") {
                            let pkg = rest.split("//").next().unwrap_or(rest).trim().to_string();
                            if !pkg.is_empty() {
                                return pkg;
                            }
                        }
                    }
                }
            }
        }
    }
    // Fallback: directory name sanitized
    wt.file_name()
        .and_then(|s| s.to_str())
        .map(|s| {
            s.chars()
                .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
                .collect::<String>()
        })
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "main".into())
}

pub fn mock_generate(req: &GenerateRequest) -> Result<GenerateResult> {
    let wt = Path::new(&req.worktree_path);
    if !wt.is_dir() {
        return Err(AgentError::Other("worktree missing".into()));
    }
    let requested_change = req
        .change_request
        .as_deref()
        .unwrap_or("none")
        .replace('\n', " ");

    let (rel, body, intended) = if req.language_hint.contains("go") || wt.join("go.mod").exists() {
        let pkg = infer_go_package(wt);
        let name = "testharbor_generated_test.go";
        let test_fn = "TestHarborGenerated";
        let body = format!(
            r#"package {pkg}

import "testing"

// Generated by TestHarbor mock agent.
// Objective: {obj}
// Criteria: {crit}
// Requested change: {change}

func {test_fn}(t *testing.T) {{
	t.Log(`TESTHARBOR_STEP {{"id":"setup","title":"准备测试上下文","input":"TestHarbor mock objective and criteria","action":"create isolated mock test context","output":"mock context is ready","assertion":"test can proceed with deterministic data"}}`)
	t.Log(`TESTHARBOR_STEP {{"id":"exercise","title":"执行业务动作","input":"mock test context","action":"run the generated test behavior","output":"business result is produced","assertion":"core behavior is observable"}}`)
	t.Log(`TESTHARBOR_STEP {{"id":"assert","title":"断言结果","input":"business result","action":"compare result with acceptance criteria","output":"pass/fail signal","assertion":"all configured acceptance criteria are satisfied"}}`)
	t.Log(`TESTHARBOR_STEP {{"id":"cleanup","title":"清理测试数据","input":"mock test context","action":"release isolated data","output":"no residue for rerun","assertion":"cleanup path is safe"}}`)
	// Placeholder assertion — dogfood-friendly green test
	if 1+1 != 2 {{
		t.Fatal("math broke")
	}}
}}
"#,
            pkg = pkg,
            obj = req.objective.replace('\n', " "),
            crit = req.acceptance_criteria.join("; ").replace('\n', " "),
            change = requested_change,
            test_fn = test_fn,
        );
        (name.to_string(), body, vec![test_fn.to_string()])
    } else {
        let name = "testharbor_generated_test.py";
        let body = format!(
            r#"# Generated by TestHarbor mock agent
# Objective: {obj}
# Requested change: {change}

def test_testharbor_generated():
    """{crit}"""
    assert True
"#,
            obj = req.objective.replace('\n', " "),
            crit = req.acceptance_criteria.join("; ").replace('\n', " "),
            change = requested_change,
        );
        (
            name.to_string(),
            body,
            vec!["test_testharbor_generated".to_string()],
        )
    };

    let path = wt.join(&rel);
    fs::write(&path, body)?;

    Ok(GenerateResult {
        mode: AgentMode::Mock,
        summary: format!(
            "Mock generator wrote {rel} for objective: {}",
            req.objective.chars().take(80).collect::<String>()
        ),
        written_files: vec![rel],
        proposed_intended_names: intended,
        test_runner: None,
        raw_path: None,
        session_id: req.session_id.clone(),
    })
}

pub fn mock_review_tests(req: &ReviewRequest) -> Result<ReviewResult> {
    let mut findings = Vec::new();

    if req.changed_paths.is_empty() {
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "coverage".into(),
            file: None,
            line: None,
            message: "No changed test files to review".into(),
            suggestion: Some("Generate tests first".into()),
        });
    }

    for p in &req.changed_paths {
        if p.contains("testharbor_generated") {
            findings.push(AgentFinding {
                severity: "warning".into(),
                category: "weak_assertion".into(),
                file: Some(p.clone()),
                line: Some(1),
                message: "Generated test may use weak/placeholder assertions".into(),
                suggestion: Some(
                    "Replace placeholder with real assertions for acceptance criteria".into(),
                ),
            });
        }
    }

    if req.acceptance_criteria.is_empty() {
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "intent".into(),
            file: None,
            line: None,
            message: "Missing acceptance criteria".into(),
            suggestion: None,
        });
    }

    let recommendation = if findings.iter().any(|f| f.severity == "error") {
        "CHANGES".into()
    } else {
        "APPROVE".into()
    };

    Ok(ReviewResult {
        mode: AgentMode::Mock,
        recommendation,
        summary: format!(
            "Mock reviewer: {} finding(s) on {} file(s)",
            findings.len(),
            req.changed_paths.len()
        ),
        findings,
        test_intent_hash: req.test_intent_hash.clone(),
    })
}

/// Deterministic Analyzer: classify from structured counters + logs (no LLM).
pub fn mock_analyze_result(req: &AnalyzeRequest) -> Result<AnalyzeResult> {
    let mut findings = Vec::new();
    let mut evidence = Vec::new();
    let mut verdict = "UNKNOWN".to_string();
    let mut confidence = "medium".to_string();

    evidence.push(format!(
        "exit={:?} parser={} complete={} consistent={} total={} pass={} fail={} empty={}",
        req.exit_code,
        req.parser,
        req.completeness,
        req.consistency,
        req.total,
        req.passed,
        req.failed,
        req.empty
    ));
    evidence.push(format!(
        "intended {}/{} observed, failed={}, missing={}",
        req.intended_observed, req.intended_count, req.intended_failed, req.intended_missing
    ));

    if req.parser == "exit-code" || req.completeness == "opaque" {
        verdict = "UNKNOWN".into();
        confidence = "low".into();
        findings.push(AgentFinding {
            severity: "info".into(),
            category: "opaque_result".into(),
            file: None,
            line: None,
            message: "Generic/exit-code 结果无法区分测试缺陷与产品缺陷".into(),
            suggestion: Some("使用 go-test-json 等结构化 parser".into()),
        });
    } else if req.exit_code == Some(0)
        && req.failed == 0
        && !req.empty
        && req.intended_count > 0
        && req.intended_observed >= req.intended_count
        && req.intended_failed == 0
        && req.intended_missing == 0
    {
        verdict = "PASS".into();
        confidence = "high".into();
        findings.push(AgentFinding {
            severity: "info".into(),
            category: "pass".into(),
            file: None,
            line: None,
            message: "结构化结果通过且 intended 全部观察".into(),
            suggestion: None,
        });
    } else if req.failure_phase.as_deref() == Some("build")
        || req.stderr_excerpt.to_lowercase().contains("build failed")
        || req.stderr_excerpt.contains("undefined:")
    {
        verdict = "TEST_BUG".into();
        confidence = "high".into();
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "build".into(),
            file: None,
            line: None,
            message: "更像编译/构建失败，优先归因为测试或生成代码问题".into(),
            suggestion: Some("RequestTestChange：修复生成测试的 package/import".into()),
        });
    } else if req.empty || req.total == 0 {
        verdict = "TEST_BUG".into();
        confidence = "medium".into();
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "empty".into(),
            file: None,
            line: None,
            message: "未收集到测试用例（Empty）".into(),
            suggestion: Some("检查 Test Profile 路径与 intended inventory".into()),
        });
    } else if req.intended_missing > 0 {
        verdict = "TEST_BUG".into();
        confidence = "high".into();
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "intended_not_observed".into(),
            file: None,
            line: None,
            message: format!(
                "{} 个 intended 测试未出现在执行结果中",
                req.intended_missing
            ),
            suggestion: Some("核对 go test 范围或重新生成/选择 intended".into()),
        });
    } else if req.failed > 0 || req.intended_failed > 0 {
        // Heuristic: assertion failures with product-like keywords → PRODUCT_BUG, else TEST_BUG
        let blob = format!("{} {}", req.stdout_excerpt, req.stderr_excerpt).to_lowercase();
        if blob.contains("connection refused")
            || blob.contains("timeout")
            || blob.contains("no such host")
            || blob.contains("dial tcp")
        {
            verdict = "ENVIRONMENT_ERROR".into();
            confidence = "medium".into();
            findings.push(AgentFinding {
                severity: "warning".into(),
                category: "environment".into(),
                file: None,
                line: None,
                message: "日志含网络/连接类错误，可能是环境问题".into(),
                suggestion: Some("MarkEnvironmentIssue 并修复依赖后重跑".into()),
            });
        } else if blob.contains("assert")
            || blob.contains("expected")
            || blob.contains("want ")
            || blob.contains("got ")
        {
            // Default to PRODUCT_BUG for assertion mismatch (product may be wrong)
            // but keep advisory — Result Reviewer may override
            verdict = "PRODUCT_BUG".into();
            confidence = "low".into();
            findings.push(AgentFinding {
                severity: "warning".into(),
                category: "assertion".into(),
                file: None,
                line: None,
                message: "断言失败：可能是产品缺陷，也可能是测试预期错误".into(),
                suggestion: Some("人工区分 PRODUCT_BUG vs TEST_BUG".into()),
            });
        } else {
            verdict = "TEST_BUG".into();
            confidence = "low".into();
            findings.push(AgentFinding {
                severity: "warning".into(),
                category: "failure".into(),
                file: None,
                line: None,
                message: "存在失败用例，证据不足，暂归 TEST_BUG".into(),
                suggestion: Some("查看完整日志与 diff".into()),
            });
        }
    } else if req.consistency == "contradictory" {
        verdict = "UNKNOWN".into();
        confidence = "high".into();
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "contradictory".into(),
            file: None,
            line: None,
            message: "退出码与结构化结果矛盾".into(),
            suggestion: Some("禁止 AcceptPass，检查 parser/命令".into()),
        });
    }

    if req.stderr_excerpt.to_lowercase().contains("flaky")
        || req.stdout_excerpt.to_lowercase().contains("flaky")
    {
        findings.push(AgentFinding {
            severity: "info".into(),
            category: "flaky_hint".into(),
            file: None,
            line: None,
            message: "日志提到 flaky，考虑多次执行后再 MarkFlaky".into(),
            suggestion: None,
        });
    }

    let summary = format!(
        "Mock Analyzer → {} (confidence={}) for objective: {}",
        verdict,
        confidence,
        req.objective.chars().take(60).collect::<String>()
    );

    Ok(AnalyzeResult {
        mode: AgentMode::Mock,
        suggested_verdict: verdict,
        confidence,
        summary,
        evidence_notes: evidence,
        findings,
        test_intent_hash: req.test_intent_hash.clone(),
    })
}

/// Independent Result Reviewer: checks analyzer against hard evidence (advisory).
pub fn mock_review_result(req: &ResultReviewRequest) -> Result<ResultReviewAgentResult> {
    let mut findings = Vec::new();
    let mut overreach = false;
    let mut recommendation = "NEEDS_HUMAN".to_string();

    // Hard evidence gates
    if req.accept_pass_enabled {
        recommendation = "ACCEPT_PASS".into();
        findings.push(AgentFinding {
            severity: "info".into(),
            category: "guard".into(),
            file: None,
            line: None,
            message: "确定性 AcceptPass Guard 已满足".into(),
            suggestion: Some("人工可 AcceptPass → Apply".into()),
        });
        if req.analyzer_verdict != "PASS" && req.analyzer_verdict != "UNKNOWN" {
            overreach = true;
            findings.push(AgentFinding {
                severity: "warning".into(),
                category: "analyzer_overreach".into(),
                file: None,
                line: None,
                message: format!(
                    "Analyzer 给出 {} 但 Guard 允许通过，可能过度推断失败",
                    req.analyzer_verdict
                ),
                suggestion: Some("以 Guard 为准，忽略失败归因".into()),
            });
        }
    } else if req.empty || req.total == 0 {
        recommendation = "CHANGE_TEST".into();
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "empty".into(),
            file: None,
            line: None,
            message: "无测试被收集，不应 AcceptPass".into(),
            suggestion: Some("RequestTestChange 或修正 Profile".into()),
        });
    } else if req.completeness != "complete" || req.consistency == "contradictory" {
        recommendation = "NEEDS_HUMAN".into();
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "incomplete".into(),
            file: None,
            line: None,
            message: format!(
                "结果不完整或不一致 ({} / {})",
                req.completeness, req.consistency
            ),
            suggestion: Some("禁止 AcceptPass".into()),
        });
    } else if req.analyzer_verdict == "ENVIRONMENT_ERROR" {
        recommendation = "NEEDS_HUMAN".into();
        findings.push(AgentFinding {
            severity: "warning".into(),
            category: "environment".into(),
            file: None,
            line: None,
            message: "Analyzer 倾向环境问题".into(),
            suggestion: Some("MarkEnvironmentIssue 后修复再 Rerun".into()),
        });
    } else if req.analyzer_verdict == "PRODUCT_BUG" {
        recommendation = "ACCEPT_FAIL".into();
        // Check overreach: if no fails, overreach
        if req.failed == 0 {
            overreach = true;
            recommendation = "NEEDS_HUMAN".into();
            findings.push(AgentFinding {
                severity: "warning".into(),
                category: "analyzer_overreach".into(),
                file: None,
                line: None,
                message: "Analyzer 标 PRODUCT_BUG 但 failed=0".into(),
                suggestion: None,
            });
        } else {
            findings.push(AgentFinding {
                severity: "info".into(),
                category: "product_bug".into(),
                file: None,
                line: None,
                message: "有失败用例且 Analyzer 倾向产品缺陷".into(),
                suggestion: Some("人工确认后 MarkProductBug 或 AcceptFail".into()),
            });
        }
    } else if req.analyzer_verdict == "TEST_BUG" {
        recommendation = "CHANGE_TEST".into();
        findings.push(AgentFinding {
            severity: "info".into(),
            category: "test_bug".into(),
            file: None,
            line: None,
            message: "Analyzer 倾向测试缺陷".into(),
            suggestion: Some("RequestTestChange".into()),
        });
    } else if req.failed > 0 {
        recommendation = "ACCEPT_FAIL".into();
        findings.push(AgentFinding {
            severity: "info".into(),
            category: "failed".into(),
            file: None,
            line: None,
            message: "存在失败，Guard 未放行 AcceptPass".into(),
            suggestion: Some("AcceptFail / MarkProductBug / 改测试".into()),
        });
    }

    // intended not fully observed
    if req.intended_count > 0 && req.intended_observed < req.intended_count {
        findings.push(AgentFinding {
            severity: "error".into(),
            category: "intended".into(),
            file: None,
            line: None,
            message: format!(
                "intended 观察不全 {}/{}",
                req.intended_observed, req.intended_count
            ),
            suggestion: Some("不可 AcceptPass".into()),
        });
        if recommendation == "ACCEPT_PASS" {
            recommendation = "NEEDS_HUMAN".into();
            overreach = true;
        }
    }

    for r in &req.accept_pass_reasons {
        if r.contains("CASE_NOT_APPROVED") || r.contains("未人工批准") {
            findings.push(AgentFinding {
                severity: "error".into(),
                category: "case_review".into(),
                file: None,
                line: None,
                message: "用例尚未人工批准".into(),
                suggestion: Some("先完成用例评审".into()),
            });
        }
    }

    let summary = format!(
        "Mock Result Reviewer → {} (analyzer={}, overreach={})",
        recommendation, req.analyzer_verdict, overreach
    );

    Ok(ResultReviewAgentResult {
        mode: AgentMode::Mock,
        recommendation,
        analyzer_overreach: overreach,
        summary,
        findings,
        test_intent_hash: req.test_intent_hash.clone(),
    })
}

