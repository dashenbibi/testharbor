const englishFromChinese = Object.fromEntries(
  Object.entries(zhCN)
    .filter(([english, chinese]) => english !== chinese && !chinese.includes("{"))
    .map(([english, chinese]) => [chinese, english]),
) as Record<string, string>;

export function normalizeLanguage(value: string | null | undefined): Language {
  const normalized = value?.trim().toLowerCase();
  return normalized === "zh" || normalized === "zh-cn" || normalized === "zh_cn"
    ? "zh-CN"
    : "en";
}

export function translate(
  language: Language,
  message: string,
  params: TranslationParams = {},
) {
  const template = language === "zh-CN"
    ? zhCN[message] ?? message
    : englishFromChinese[message] ?? message;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : placeholder,
  );
}

export function setActiveLanguage(language: Language) {
  activeLanguage = language;
}

export function tr(message: string, params?: TranslationParams) {
  return translate(activeLanguage, message, params);
}
